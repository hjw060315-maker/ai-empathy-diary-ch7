// 규칙 기반 위기 표현 감지. AI와 무관하게 동작한다(PRD 6.2).
// 놓침 방지 우선: 애매하면 true 쪽으로 기운다. 공백·문장부호는 지우고 검사한다.

const PATTERNS: RegExp[] = [
  // 자살·극단적 선택
  /자살/,
  /극단적(인)?선택/,
  /목숨을?(끊|버리|던지)/,
  /스스로(목숨|생을|삶을)/,
  /생을?(마감|끝내|끝낼|포기)/,
  /삶을?(마감|끝내|끝낼|포기)/,
  /세상을?(떠나|등지)/,
  /유서/,
  // 죽고 싶음
  /죽고(싶|십|자)/,
  /죽어(버리|버릴|야겠|야지|야할|볼까|도될|도좋)/,
  /죽을(까|래|거야|것같|결심|생각|방법)/,
  /죽는(게|것이|편이)(낫|좋|쉬)/,
  /죽는(방법|법)/,
  /뒈지고싶/,
  /없어지고(싶|만싶)/,
  /사라지고(싶|만싶)/,
  /사라져버리고/,
  /살기(싫|가싫)/,
  /살고싶지(않|가않)/,
  /더는?(살고싶|살수없|살기싫|못살)/,
  /살아갈(이유|자신|힘|의미)(가|이)?(없|모르)/,
  /살(이유|의미)(가|를)?(없|모르|잃)/,
  /태어나지(말|않았)/,
  /내가(없는|없어지는|사라지는)(게|편이|것이)(더)?(낫|나을|나아|좋)/,
  /(다|모두)끝내고싶/,
  /이제(그만)?(다)?끝내(고싶|자|야겠|버리)/,
  // 자해
  /자해/,
  /자살시도/,
  /손목을?(긋|그었|그어)/,
  /(칼|면도날|커터)(로|을|를)?(몸|팔|손목|허벅지)?(을|를)?(긋|그었|그어)/,
  /몸에?(상처를?)?(내|냈)(고싶|려고|볼까)/,
  /(투신|뛰어내리)(하고싶|할까|고싶|려고|볼까|어버리)/,
  /목을?(매|맬|매달)/,
  /(번개탄|연탄)(을|를)?(피우|피워|사)/,
];

/** 부정형(예: "죽고 싶지 않다")이라도 놓치지 않기 위해 부정은 따로 걸러 내지 않는다. */
export function detectCrisisByRules(content: string): boolean {
  if (typeof content !== "string" || content === "") return false;
  const text = content
    .normalize("NFKC")
    .toLowerCase()
    .replace(/[\s.,!?~…·'"“”‘’()[\]{}\-_ㅠㅜ]+/g, "");
  return PATTERNS.some((p) => p.test(text));
}
